"""Before/after summary for evals/EVAL_RESULTS.md.

Reads the Baseline and After tables, checks them for gaps and for answers that do
not match the expected value, and prints accuracy and tool-call statistics
for both runs side by side. Numbers are reported exactly as recorded.

Usage (from the repo root):
    uv run python evals/summarize_results.py          # print the summary
    uv run python evals/summarize_results.py --write  # also write it into the file
"""

import argparse
import statistics
import sys
from dataclasses import dataclass
from pathlib import Path

RESULTS = Path(__file__).resolve().parent / "EVAL_RESULTS.md"
MARKER = "<!-- Generated by evals/summarize_results.py --write -->"
SECTIONS = {"before": "## Baseline", "after": "## After"}


@dataclass
class Row:
    q: int
    expected: str
    answer: str
    correct: bool | None
    tool_calls: int | None


def parse_table(text: str, heading: str) -> list[Row]:
    start = text.index(heading)
    end = text.find("\n## ", start + 1)
    lines = text[start : end if end != -1 else None].splitlines()
    rows = []
    for line in lines:
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 5 or not cells[0].isdigit():
            continue
        correct = {"yes": True, "y": True, "no": False, "n": False}.get(
            cells[3].lower()
        )
        rows.append(
            Row(
                q=int(cells[0]),
                expected=cells[1],
                answer=cells[2],
                correct=correct,
                tool_calls=int(cells[4]) if cells[4].isdigit() else None,
            )
        )
    return rows


def check(rows: list[Row], label: str) -> list[str]:
    problems = []
    for r in rows:
        if not r.answer or r.correct is None or r.tool_calls is None:
            problems.append(
                f"{label} Q{r.q}: answer, Correct (Yes/No) or Tool calls is empty"
            )
            continue
        matches = (
            r.answer.replace(" ", "").lower() == r.expected.replace(" ", "").lower()
        )
        if matches != r.correct:
            problems.append(
                f"{label} Q{r.q}: marked {'Yes' if r.correct else 'No'} but answer "
                f"'{r.answer}' {'matches' if matches else 'does not match'} '{r.expected}'"
            )
    if len(rows) != 10:
        problems.append(f"{label}: expected 10 rows, found {len(rows)}")
    return problems


def stats(rows: list[Row]) -> dict:
    calls = [r.tool_calls for r in rows if r.tool_calls is not None]
    return {
        "accuracy": f"{sum(bool(r.correct) for r in rows)}/{len(rows)}",
        "median_calls": statistics.median(calls) if calls else None,
        "total_calls": sum(calls),
        "range_calls": f"{min(calls)} to {max(calls)}" if calls else "n/a",
    }


def fmt(v: object) -> str:
    if v is None:
        return "n/a"
    return f"{v:g}" if isinstance(v, float) else str(v)


def summary(before: list[Row], after: list[Row]) -> str:
    b, a = stats(before), stats(after)
    lines = [
        "| Measure | Before | After |",
        "|---|---|---|",
        f"| Accuracy | {b['accuracy']} | {a['accuracy']} |",
        f"| Median tool calls | {fmt(b['median_calls'])} | {fmt(a['median_calls'])} |",
        f"| Total tool calls | {b['total_calls']} | {a['total_calls']} |",
        f"| Tool calls range | {b['range_calls']} | {a['range_calls']} |",
        "",
        "Per question (tool calls before -> after, correctness):",
        "",
    ]
    by_q = {r.q: r for r in after}
    for r in before:
        n = by_q.get(r.q)
        if n is None:
            continue
        change = ""
        if r.correct and not n.correct:
            change = " **got worse: now incorrect**"
        elif not r.correct and n.correct:
            change = " (now correct)"
        lines.append(
            f"- Q{r.q}: {fmt(r.tool_calls)} -> {fmt(n.tool_calls)}, "
            f"{'correct' if r.correct else 'incorrect'} -> "
            f"{'correct' if n.correct else 'incorrect'}{change}"
        )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Before/after eval summary.")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    text = RESULTS.read_text()
    before = parse_table(text, SECTIONS["before"])
    after = parse_table(text, SECTIONS["after"])
    problems = check(before, "Baseline") + check(after, "After")
    if problems:
        print("Fix these before summarizing:")
        print("\n".join(f"- {p}" for p in problems))
        return 1

    out = summary(before, after)
    print(out)
    if args.write:
        head = text[: text.index(MARKER) + len(MARKER)]
        RESULTS.write_text(head + "\n\n" + out + "\n")
        print(f"\nwrote {RESULTS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
